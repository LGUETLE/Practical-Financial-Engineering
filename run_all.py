"""
Regenerates every result in results/ (and the LaTeX/CSV tables and plots in output_tables/ and
output_plots/) by running all experiment scripts in order. Writes results/run_info.md with the
software versions and the runtime of each script.

Usage:  python run_all.py            (needs network access only if data/ has no cached prices)
"""
from __future__ import annotations

import os
import platform
import time
from datetime import date

import matplotlib
import numpy as np
import pandas as pd
import scipy

ROOT = os.path.dirname(os.path.abspath(__file__))


def main() -> None:
    os.chdir(ROOT)
    import bounds_engine
    import seed_study
    import empirical_engine
    import stresstest_engine
    import theory_engine

    steps = [("theory_engine.py", theory_engine.main),
             ("bounds_engine.py", bounds_engine.main),
             ("empirical_engine.py", empirical_engine.main),
             ("stresstest_engine.py", stresstest_engine.main),
             ("seed_study.py", seed_study.main)]
    runtimes = []
    t_all = time.perf_counter()
    for name, fn in steps:
        print(f"\n{'=' * 70}\nRunning {name}\n{'=' * 70}")
        t0 = time.perf_counter()
        fn()
        runtimes.append((name, time.perf_counter() - t0))
    total = time.perf_counter() - t_all

    lines = ["# Run information", "",
             f"Generated by `run_all.py` on {date.today().isoformat()}.", "",
             f"- Python {platform.python_version()}, numpy {np.__version__}, scipy "
             f"{scipy.__version__}, pandas {pd.__version__}, matplotlib {matplotlib.__version__}",
             f"- Machine: {platform.machine()}, {platform.system()} {platform.release()}", "",
             "| Script | Runtime (s) |", "|---|---:|"]
    lines += [f"| `{n}` | {t:.1f} |" for n, t in runtimes]
    lines += [f"| total | {total:.1f} |", ""]
    with open(os.path.join("results", "run_info.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("\n" + "\n".join(lines))


if __name__ == "__main__":
    main()
